"""One-off: POST full demo article to running translate API."""
import sys
import time

import requests

sys.stdout.reconfigure(encoding="utf-8")

TEXT = """الأسد والنسر والقرد حيوانات الغابة. الحصان والجمل والحمار يمشيان ويأكلان. القط والكلب والبقرة والخروف حيوانات.

الطالب يشاهد الأحمر والأزرق والأخضر والأصفر. الأبيض والأسود والبني والبرتقالي ألوان. الوردي والبنفسجي والذهبي والفضي ألوان.

الصيف والربيع والخريف والشتاء الفصول الأربعة. الصيف شمس ودرجات حرارة مرتفعة. الشتاء ثلج ورياح وغيوم وضباب ورعد وبرق.

المسلم يحفظ الصلاة والدعاء. الحج والزكاة والصيام دين. الجنة والنار يوم القيامة.

الطبيب يساعد المريض والصيدلي يعرف الدواء. المهندس يبني والكهربائي يصلح. النجار والخياط والميكانيكي يعملان.

الأم تشتري اللحم والدجاج والسمك والبيضة. المنسف والمقلوبة والملوخية والفلافل طعام. الشوكولاتة والكعكة والبودنغ والمهلبية حلويات.

المريض يشرب الدواء وينام. الطبيب يعرف الحرارة والصداع والمغص. طبيب أسنان وطبيب عيون يساعدان المريض.

واحد واثنان وثلاثة وأربعة وخمسة أرقام. ستة وسبعة وثمانية وتسعة وعشرة أرقام. عشرون وثلاثون ومائة وألف ومليون أرقام.

الطالب يدرس مادة الرياضيات ومادة العلوم. المعلم يدرّس مادة التاريخ ومادة الجغرافيا. الطالب يتعلم مادة اللغة العربية ومادة الفيزياء.

الوزير يطوّر وزارة الصحة ووزارة التربية والتعليم. رئيس الوزراء يناقش ويعمل. مجلس النواب ومجلس الأعيان يناقشان."""

API = "http://127.0.0.1:8000/api/v1/translate/?mode=per_token"
H = {"Origin": "http://127.0.0.1:5500", "Content-Type": "application/json"}
print("len", len(TEXT))
t0 = time.time()
r = requests.post(API, json={"text": TEXT}, headers=H, timeout=300)
print("status", r.status_code, "sec", round(time.time() - t0, 1))
if r.ok:
    v = r.json().get("videos", [])
    play = sum(1 for x in v if x.get("storage_url"))
    print("videos", len(v), "playable", play)
else:
    print(r.text[:400])
